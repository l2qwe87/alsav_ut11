  async searchWebHelp(query) {
    try {
      // Попытка поиска в онлайн-ресурсах 1С
      const searchUrls = [
        `https://its.1c.ru/db/v8std#content:${query}`,
        `https://v8.1c.ru/overview/`,
        `https://infostart.ru/search/?q=${encodeURIComponent(query)}`
      ];

      const results = [];
      
      for (const url of searchUrls) {
        try {
          const response = await fetch(url, { 
            timeout: 5000,
            headers: { 'User-Agent': 'Mozilla/5.0' }
          });
          
          if (response.ok) {
            results.push({
              url: url,
              status: "Доступен",
              description: `Онлайн-справка по запросу: ${query}`
            });
          }
        } catch (error) {
          results.push({
            url: url,
            status: "Недоступен",
            error: error.message
          });
        }
      }

      return {
        content: [
          {
            type: "text",
            text: JSON.stringify({
              query,
              webResults: results,
              note: "Для получения полной информации рекомендуется использовать официальную документацию 1С"
            }, null, 2)
          }
        ]
      };
    } catch (error) {
      return {
        content: [
          {
            type: "text",
            text: `Ошибка при поиске в онлайн-справке: ${error.message}`
          }
        ]
      };
    }
  }

